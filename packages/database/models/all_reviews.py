import uuid
from datetime import datetime
from decimal import Decimal
from typing import Any, Optional

from sqlalchemy import (
    Boolean, CheckConstraint, DateTime, FetchedValue, ForeignKey, Index, Integer, Numeric, Text,
    false, func, text,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column

from ..base import Base
from ..ddl import add_alnum_id_trigger, add_review_edit_trigger, enable_rls


class Review(Base):
    __tablename__ = "all_reviews"
    __table_args__ = (
        Index("ix_all_reviews_dish_id_review_id", "dish_id", "review_id"),
        Index("ix_all_reviews_user_id_review_id", "user_id", "review_id"),
        CheckConstraint(
            "rating >= 0.5 AND rating <= 5 AND rating * 2 = trunc(rating * 2)",
            name="ck_all_reviews_rating_half_stars",
        ),
        CheckConstraint("like_count >= 0", name="ck_all_reviews_like_count_nonnegative"),
        CheckConstraint("dislike_count >= 0", name="ck_all_reviews_dislike_count_nonnegative"),
    )

    review_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=text("gen_random_uuid()")
    )
    # Generated by the database on insert, e.g. REV-7K3X9P2M
    review_alphanumeric_id: Mapped[str] = mapped_column(
        Text, nullable=False, unique=True, server_default=FetchedValue()
    )
    dish_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("all_dishes.dish_id"), nullable=False
    )
    order_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("orders.order_id"), nullable=False
    )
    user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("users.user_id"), nullable=False
    )
    # Half stars: 0.5, 1.0, 1.5 ... 5.0
    rating: Mapped[Decimal] = mapped_column(Numeric(2, 1), nullable=False)
    review_text: Mapped[Optional[str]] = mapped_column(Text)
    # List of Supabase Storage URLs
    images: Mapped[list[Any]] = mapped_column(
        JSONB, nullable=False, server_default=text("'[]'::jsonb")
    )
    anonymous_flag: Mapped[bool] = mapped_column(Boolean, nullable=False, server_default=false())
    review_time: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )
    # Set by the database when rating/text/images/anonymous_flag change
    last_edited_time: Mapped[Optional[datetime]] = mapped_column(
        DateTime(timezone=True), server_onupdate=FetchedValue()
    )
    like_count: Mapped[int] = mapped_column(Integer, nullable=False, server_default=text("0"))
    dislike_count: Mapped[int] = mapped_column(Integer, nullable=False, server_default=text("0"))

    def __repr__(self) -> str:
        return f"<Review {self.review_alphanumeric_id} {self.rating}>"


add_alnum_id_trigger(Review.__table__, "review_alphanumeric_id", "REV-")
add_review_edit_trigger(Review.__table__)
enable_rls(Review.__table__)
