import uuid
from datetime import datetime
from typing import Optional

from sqlalchemy import (
    Boolean, CheckConstraint, DateTime, FetchedValue, ForeignKey, Index, Integer, Text, false,
    func, text,
)
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column

from ..base import Base
from ..ddl import add_alnum_id_trigger, enable_rls


class Order(Base):
    __tablename__ = "orders"
    __table_args__ = (
        Index("ix_orders_user_id_order_id", "user_id", "order_id"),
        CheckConstraint("portion_count > 0", name="ck_orders_portion_count_positive"),
    )

    order_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=text("gen_random_uuid()")
    )
    # Generated by the database on insert, e.g. ORD-7K3X9P2M
    order_alphanumeric_id: Mapped[str] = mapped_column(
        Text, nullable=False, unique=True, server_default=FetchedValue()
    )
    kitchen_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("all_kitchens.kitchen_id"), nullable=False
    )
    dish_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("all_dishes.dish_id"), nullable=False
    )
    user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("users.user_id"), nullable=False
    )
    portion_count: Mapped[int] = mapped_column(Integer, nullable=False)
    order_time: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )
    order_status: Mapped[str] = mapped_column(Text, nullable=False)
    # Payment gateway ID (e.g. "pay_..."), so text rather than uuid
    payment_id: Mapped[Optional[str]] = mapped_column(Text)
    refund_flag: Mapped[bool] = mapped_column(Boolean, nullable=False, server_default=false())

    def __repr__(self) -> str:
        return f"<Order {self.order_alphanumeric_id} {self.order_status!r}>"


add_alnum_id_trigger(Order.__table__, "order_alphanumeric_id", "ORD-")
enable_rls(Order.__table__)
