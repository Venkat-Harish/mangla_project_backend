import uuid
from datetime import datetime
from typing import Any, Optional

from sqlalchemy import (
    Boolean, CheckConstraint, DateTime, FetchedValue, ForeignKey, Index, Text, false, func, text,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column

from ..base import Base
from ..ddl import add_alnum_id_trigger, add_last_edited_trigger, add_post_deleted_time_trigger, enable_rls


class Post(Base):
    __tablename__ = "posts"
    __table_args__ = (
        Index("ix_posts_kitchen_id_post_id", "kitchen_id", "post_id"),
        Index("ix_posts_post_deleted_flag_post_id", "post_deleted_flag", "post_id"),
        CheckConstraint(
            "post_deleted_flag = (post_deleted_time IS NOT NULL)",
            name="ck_posts_deleted_time_matches_flag",
        ),
    )

    post_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=text("gen_random_uuid()")
    )
    # Generated by the database on insert, e.g. PST-7K3X9P2M
    post_alphanumeric_id: Mapped[str] = mapped_column(
        Text, nullable=False, unique=True, server_default=FetchedValue()
    )
    kitchen_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("all_kitchens.kitchen_id"), nullable=False
    )
    description: Mapped[Optional[str]] = mapped_column(Text)
    # List of Supabase Storage URLs (images and/or videos)
    media_urls: Mapped[list[Any]] = mapped_column(
        JSONB, nullable=False, server_default=text("'[]'::jsonb")
    )
    posted_time: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )
    # Set by the database when description or media_urls change
    last_edited_time: Mapped[Optional[datetime]] = mapped_column(
        DateTime(timezone=True), server_onupdate=FetchedValue()
    )
    # Soft delete: the row stays; set the flag and the database stamps post_deleted_time
    post_deleted_flag: Mapped[bool] = mapped_column(Boolean, nullable=False, server_default=false())
    post_deleted_time: Mapped[Optional[datetime]] = mapped_column(
        DateTime(timezone=True), server_default=FetchedValue(), server_onupdate=FetchedValue()
    )

    def __repr__(self) -> str:
        return f"<Post {self.post_alphanumeric_id} deleted={self.post_deleted_flag}>"


add_alnum_id_trigger(Post.__table__, "post_alphanumeric_id", "PST-")
add_last_edited_trigger(Post.__table__, "description", "media_urls")
add_post_deleted_time_trigger(Post.__table__)
enable_rls(Post.__table__)
