import uuid
from typing import Optional

from sqlalchemy import FetchedValue, ForeignKey, Index, Text, text
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column

from ..base import Base
from ..ddl import add_alnum_id_trigger, enable_rls


class Kitchen(Base):
    __tablename__ = "all_kitchens"
    __table_args__ = (
        Index("ix_all_kitchens_society_id_kitchen_id", "society_id", "kitchen_id"),
    )

    kitchen_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=text("gen_random_uuid()")
    )
    kitchen_name: Mapped[str] = mapped_column(Text, nullable=False)
    # FK to societies once that table exists
    society_id: Mapped[Optional[uuid.UUID]] = mapped_column(UUID(as_uuid=True))
    user_id1: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("users.user_id"), nullable=False
    )
    user_id2: Mapped[Optional[uuid.UUID]] = mapped_column(
        UUID(as_uuid=True), ForeignKey("users.user_id")
    )
    user_id3: Mapped[Optional[uuid.UUID]] = mapped_column(
        UUID(as_uuid=True), ForeignKey("users.user_id")
    )
    # Generated by the database on insert, e.g. KIT-7K3X9P2M
    kitchen_alphanumeric_id: Mapped[str] = mapped_column(
        Text, nullable=False, unique=True, server_default=FetchedValue()
    )

    def __repr__(self) -> str:
        return f"<Kitchen {self.kitchen_alphanumeric_id} {self.kitchen_name!r}>"


add_alnum_id_trigger(Kitchen.__table__, "kitchen_alphanumeric_id", "KIT-")
enable_rls(Kitchen.__table__)
